import json


def create_scene_prompt(scene):

    # ---------------------------------------------
    # GET INFORMATION FROM SCENE UNDERSTANDING
    # ---------------------------------------------

    event = ", ".join(
        scene.get("event", [])
    )

    time = ", ".join(
        scene.get("time", [])
    )

    people = ", ".join(
        scene.get("people", [])
    )

    locations = ", ".join(
        scene.get("locations", [])
    )

    objects = ", ".join(
        scene.get("objects", [])
    )

    actions = ", ".join(
        scene.get("actions", [])
    )

    conditions = ", ".join(
        scene.get("conditions", [])
    )

    evidence = ", ".join(
        scene.get("evidence", [])
    )

    # ---------------------------------------------
    # CREATE FLUX PROMPT
    # ---------------------------------------------

    prompt = f"""
Realistic forensic reconstruction of a
{event if event else 'crime scene'}.

Scene location:
{locations if locations else 'unspecified location'}.

Time:
{time if time else 'unspecified time'}.

People involved:
{people if people else 'unspecified people'}.

Important objects:
{objects if objects else 'relevant objects'}.

Actions:
{actions if actions else 'unspecified actions'}.

Conditions:
{conditions if conditions else 'no specific conditions provided'}.

Evidence visible at the scene:
{evidence if evidence else 'no specific evidence identified'}.

Create a realistic crime-scene reconstruction based only on the
information provided.

Maintain logical spatial relationships between people, objects,
vehicles, evidence, and the surrounding environment.

Use realistic lighting, realistic proportions, natural positioning,
and a detailed forensic reconstruction style.

Do not add unrelated objects or events that are not supported by
the scene information.
"""

    return prompt.strip()


# =============================================
# MAIN PROGRAM
# =============================================

if __name__ == "__main__":

    # Read the output generated by scene_understanding.py
    with open(
        "../text_module/scene_understanding_output.json",
        "r"
    ) as file:

        scene = json.load(file)

    # Generate prompt
    prompt = create_scene_prompt(scene)

    # Display prompt
    print("\n==========================================")
    print("          GENERATED SCENE PROMPT")
    print("==========================================")

    print(prompt)

    # Save prompt
    with open(
        "scene_prompt.txt",
        "w"
    ) as file:

        file.write(prompt)

    print(
        "\nPrompt saved to scene_prompt.txt"
    )